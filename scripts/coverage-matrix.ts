// Generates docs/COVERAGE_MATRIX.md: every official KCNA competency against the
// lessons, questions, labs and practice items that cover it. Run with --check in
// CI to fail when the committed matrix is stale.
import { readFileSync, writeFileSync } from 'node:fs';
import {
  DOMAINS,
  OBJECTIVES,
  CURRICULUM_VERIFIED_AT,
  flashcards,
  labs,
  lessons,
  questions,
  terminalChallenges,
  troubleshootingScenarios,
  yamlChallenges,
} from '@kcna/content';

const out: string[] = [];
out.push('# KCNA curriculum coverage matrix', '');
out.push(`Generated by \`npm run coverage:matrix\` from the content package. Curriculum verified against the CNCF KCNA curriculum on ${CURRICULUM_VERIFIED_AT}.`, '');
out.push('| Domain | Weight | Competency | Lessons | Questions | Labs (full / design) | Terminal | YAML | Troubleshooting | Flashcards | Status |');
out.push('|---|---:|---|---:|---:|---|---:|---:|---:|---:|---|');
const gaps: string[] = [];
for (const d of DOMAINS)
  for (const oid of d.objectives) {
    const o = OBJECTIVES.find((x) => x.id === oid)!;
    const ls = lessons.filter((l) => l.objectives.includes(oid));
    const qs = questions.filter((q) => q.objective === oid);
    const lf = labs.filter((l) => l.objectives.includes(oid) && l.status === 'full').length;
    const ld = labs.filter((l) => l.objectives.includes(oid) && l.status === 'design').length;
    const t = terminalChallenges.filter((x) => x.objective === oid).length;
    const y = yamlChallenges.filter((x) => x.objective === oid).length;
    const ts = troubleshootingScenarios.filter((x) => x.objective === oid).length;
    const fc = flashcards.filter((x) => x.objective === oid).length;
    const issues: string[] = [];
    if (!ls.length) issues.push('no lesson');
    if (qs.length < 6) issues.push(`only ${qs.length} questions`);
    if (!lf && !t && !y && !ts) issues.push('no hands-on practice');
    if (issues.length) gaps.push(`- **${o.name}**: ${issues.join(', ')}`);
    out.push(`| ${d.name} | ${d.weight}% | ${o.name} | ${ls.length} | ${qs.length} | ${lf} / ${ld} | ${t} | ${y} | ${ts} | ${fc} | ${issues.length ? '⚠ ' + issues.join('; ') : '✓ covered'} |`);
  }
out.push('', '## Gaps and thin areas', '');
out.push(gaps.length ? gaps.join('\n') : 'None — every competency has lessons, at least 6 questions and hands-on practice.');
out.push('', '## Lessons by competency', '');
for (const o of OBJECTIVES) {
  const ls = lessons.filter((l) => l.objectives.includes(o.id));
  out.push(`- **${o.name}** (${o.id}): ${ls.map((l) => `${l.title} [${l.scope}]`).join('; ')}`);
}
out.push('', '## Question distribution by domain', '');
for (const d of DOMAINS) {
  const n = questions.filter((q) => q.domain === d.id).length;
  out.push(`- ${d.name}: ${n} questions (${Math.round((n / questions.length) * 100)}% of bank vs ${d.weight}% exam weight)`);
}
const text = out.join('\n') + '\n';
const path = new URL('../docs/COVERAGE_MATRIX.md', import.meta.url);
if (process.argv.includes('--check')) {
  const cur = (() => {
    try {
      return readFileSync(path, 'utf8');
    } catch {
      return '';
    }
  })();
  if (cur !== text) {
    console.error('docs/COVERAGE_MATRIX.md is out of date. Run: npm run coverage:matrix');
    process.exit(1);
  }
  console.log('Coverage matrix is up to date.');
} else {
  writeFileSync(path, text);
  console.log(text);
}
